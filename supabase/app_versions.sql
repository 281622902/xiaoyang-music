-- 在 Supabase SQL Editor 执行。发布版本由控制台或可信后台完成，客户端只有读取权限。
create table if not exists public.app_versions (
  id bigint generated by default as identity primary key,
  platform text not null check (platform in ('windows', 'android')),
  version text not null check (
    version ~ '^(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(-[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?(\+[0-9A-Za-z-]+(\.[0-9A-Za-z-]+)*)?$'
  ),
  download_url text not null check (download_url ~* '^https?://[^[:space:]]+$'),
  release_notes text not null default '',
  constraint app_versions_platform_version_unique unique (platform, version)
);

create index if not exists app_versions_platform_id_idx
  on public.app_versions (platform, id);

alter table public.app_versions enable row level security;
revoke all on table public.app_versions from anon, authenticated;
grant select on table public.app_versions to anon, authenticated;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'app_versions'
      and policyname = 'app_versions_public_read'
  ) then
    create policy app_versions_public_read
      on public.app_versions for select to anon, authenticated
      using (true);
  end if;
end $$;

